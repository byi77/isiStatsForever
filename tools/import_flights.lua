-- Runs in standalone Lua (io, os, loadfile), not in the WoW client.
-- Takes the flight times measured in game into the shipped table FlightSeeds.lua:
--   lua tools/import_flights.lua <dir> <SavedVariables file> [table path]
-- The SavedVariables file is the account-wide isiStatsForever.lua; only its
-- flight times are read (IsiStatsDB.flights[faction][from][to] = seconds).
-- `table path` reads another table with the same layout instead, e.g.
-- "SomeDB.global". Times from the file replace shipped ones of the same route
-- (newer measurement); all other shipped routes stay.
local dir, file, path = ...
assert(dir and file, "usage: lua tools/import_flights.lua <dir> <SavedVariables file> [table path]")
path = path or "IsiStatsDB.flights"

local function load(fileName, env)
  local chunk = assert(loadfile(fileName, "t", env))
  if setfenv then
    setfenv(chunk, env)
  end
  return chunk
end

local saved = {}
load(file, saved)()
local source = saved
for key in path:gmatch("[^%.]+") do
  source = type(source) == "table" and source[key] or nil
end
assert(type(source) == "table", "no table " .. path .. " in " .. file)

local ns = {}
load(dir .. "/FlightSeeds.lua", {})("isiStatsForever", ns)
local seeds = ns.FlightSeeds or {}

local added, changed = 0, 0
for faction, routes in pairs(source) do
  if type(faction) == "string" and type(routes) == "table" then
    seeds[faction] = seeds[faction] or {}
    for from, list in pairs(routes) do
      if type(from) == "number" and type(list) == "table" then
        for to, seconds in pairs(list) do
          if type(to) == "number" and type(seconds) == "number" and seconds > 0 then
            seeds[faction][from] = seeds[faction][from] or {}
            local old = seeds[faction][from][to]
            if old == nil then
              added = added + 1
            elseif old ~= math.floor(seconds + 0.5) then
              changed = changed + 1
            end
            seeds[faction][from][to] = math.floor(seconds + 0.5)
          end
        end
      end
    end
  end
end

local function sortedKeys(t)
  local keys = {}
  for k in pairs(t) do
    keys[#keys + 1] = k
  end
  table.sort(keys) -- one table holds only faction names or only node IDs
  return keys
end

local out = {}
local function emit(line)
  out[#out + 1] = line
end
emit("local _, ns = ...")
emit("")
emit("-- Flight times shipped with the addon: whole flights measured in game,")
emit("-- ns.FlightSeeds[faction][fromNodeID][toNodeID] = seconds (the game's flight")
emit("-- point IDs). Flights.Get uses them only for a route this install never flew")
emit("-- itself. Generated by tools/import_flights.lua - do not edit by hand.")
emit("ns.FlightSeeds = {")
local total = 0
for _, faction in ipairs(sortedKeys(seeds)) do
  emit(string.format("  %s = {", faction))
  for _, from in ipairs(sortedKeys(seeds[faction])) do
    local parts = {}
    for _, to in ipairs(sortedKeys(seeds[faction][from])) do
      parts[#parts + 1] = string.format("[%d] = %d", to, seeds[faction][from][to])
      total = total + 1
    end
    emit(string.format("    [%d] = { %s },", from, table.concat(parts, ", ")))
  end
  emit("  },")
end
emit("}")
local f = assert(io.open(dir .. "/FlightSeeds.lua", "wb"))
f:write(table.concat(out, "\n") .. "\n")
f:close()
print(string.format("flight seeds: %d routes (%d new, %d changed)", total, added, changed))
